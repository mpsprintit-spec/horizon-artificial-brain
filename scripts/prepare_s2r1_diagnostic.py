#!/usr/bin/env python3
"""Generate a non-installing trace of the exact S2 native candidate search.

Only enabled with -tags horizon_s2r1. The source hash and each insertion are
checked. All native scoring/admission arithmetic is retained; execution stops
before installation, diagnosis recording, WAL writes, or structural growth.
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'services/ai/knowledge/neural_metric_learning.go'
OUTPUT = ROOT / 'services/ai/knowledge/zz_s2r1_trace_generated.go'
EXPECTED = '5cbd936e59145868a152c8e6f0ff7b08cf1a6fd30bb1ede579b2bb4136061db6'


def generate():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != EXPECTED:
        raise ValueError('native learner changed: re-audit before tracing')
    text = raw.decode()
    prefix, _ = text.split('\n\tif selected {\n\t\td.Committed = true', 1)
    def replace(old, new):
        nonlocal prefix
        if prefix.count(old) != 1:
            raise ValueError('instrumentation anchor is not unique: ' + old)
        prefix = prefix.replace(old, new)
    replace('func (k *KnowledgeBase) learnNMetric(',
            'func (k *KnowledgeBase) s2r1TraceMetric(')
    replace('e CompositionExposure, at time.Time) error {',
            'e CompositionExposure, at time.Time, trace *S2R1Trace) error {')
    replace('before := k.loadNModel(bank, queries)',
            'before := k.loadNModel(bank, queries)\n\ttrace.before = nClone(before)\n\ttrace.Before = before')
    replace('all := append(slices.Clone(fit), check...)',
            'all := append(slices.Clone(fit), check...)\n\ttrace.fit, trace.check = fit, check\n\ttrace.witnesses = state.Witnesses\n\ttrace.Evidence = s2r1Evidence(fit, check, state.Witnesses)')
    replace('k.finishNMetricDiagnosis(d, e.Input.RequiredPrecision, nMetricMaximumError(before, query, all), at)',
            'trace.Diagnosis = d')
    # The conflict arm can write uncertainty metadata in production. It is
    # unreachable for these verified commands, and forbidden in this tracer.
    replace('if query[0] != 0 {', 'if false && query[0] != 0 {')
    replace('eligible := len(why) == 0',
            'eligible := len(why) == 0\n\t\t\ttrace.capture(kind, feature, before, best, m, fit, check, state.Witnesses, bestErr, bestBound, goal, why, valid, duplicate, knownGain, precisionGain, errorGain)')
    replace('kind := "missing-direction"',
            'trace.ResidualAxis = slices.Clone(axis)\n\t\t\tkind := "missing-direction"')
    anchor = 'sort.SliceStable(candidates, func(i, j int) bool { return candidates[i].score > candidates[j].score })'
    replace(anchor, anchor + '\n\t\tfor rank, p := range candidates {\n\t\t\ttrace.Ranking = append(trace.Ranking, map[string]any{"rank": rank + 1, "parents": []NodeID{before.Circuits[p.a].Meta.Node, before.Circuits[p.b].Meta.Node}, "kind": p.kind, "score": p.score, "within_top8": rank < 8})\n\t\t}')
    prefix += '\n\td.Committed = selected\n\td.AfterError = bestErr\n\ttrace.Diagnosis = d\n\ttrace.best = nClone(best)\n\ttrace.Best = best\n\ttrace.BestBound = s2r1Number(bestBound)\n\treturn nil\n}\n'
    OUTPUT.write_text('//go:build horizon_s2r1\n\n// Code generated by scripts/prepare_s2r1_diagnostic.py; DO NOT EDIT.\n// Native source SHA-256: ' + EXPECTED + '\n' + prefix)
    return OUTPUT


if __name__ == '__main__':
    print(generate())
